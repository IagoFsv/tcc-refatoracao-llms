class AnimationSettings:
    def __init__(self, width_rectangle, height_reference):
        self.width_rectangle = width_rectangle
        self.height_reference = height_reference

    def __str__(self):
        return f"width_rectangle={self.width_rectangle}, height_reference={self.height_reference}"

def draw_array(display, arrTexts, settings):
    textos = tuple(texto.valor for texto in arrTexts)
    display.quadros.append((textos, tuple(), settings.width_rectangle, settings.height_reference))

def compare_elements(display, arrTexts, settings, i, j):
    draw_array(display, arrTexts, settings)
    clock.tick(FREQUENCY_CLOCK)
    draw_array(display, arrTexts, settings, [i, j])
    clock.tick(FREQUENCY_CLOCK)
    if (arr[i] > arr[j] and i < j) or (arr[i] < arr[j] and i > j):
        return False
    return True

def compare_and_swap(display, arrTexts, settings, i, j):
    swapped = False
    draw_array(display, arrTexts, settings)
    clock.tick(FREQUENCY_CLOCK)
    draw_array(display, arrTexts, settings, [i, j])
    clock.tick(FREQUENCY_CLOCK)
    if (arr[i] > arr[j] and i < j) or (arr[i] < arr[j] and i > j):
        swap_elements(arr, arrTexts, i, j)
        draw_array(display, arrTexts, settings, [i, j])
        clock.tick(FREQUENCY_CLOCK)
        swapped = True
    draw_array(display, arrTexts, settings)
    clock.tick(FREQUENCY_CLOCK)
    return swapped

def simulate_quicksort(arr, arrTexts, display, settings):
    # generated by github copilot
    def partition(arr, arrTexts, display, settings, low, high):
        i = low - 1
        # pivot = arr[high]
        for j in range(low, high):
            if compare_elements(
                display, arrTexts, settings, arr, j, high
            ):
                i += 1
                if i != j:
                    compare_and_swap(
                        display, arrTexts, settings, i, j
                    )
        if i + 1 != high:
            compare_and_swap(
                display, arrTexts, settings, i + 1, high
            )
        return i + 1

    def quicksort(arr, arrTexts, display, settings, low, high):
        if low < high:
            pi = partition(
                arr, arrTexts, display, settings, low, high
            )
            quicksort(
                arr, arrTexts, display, settings, low, pi - 1
            )
            quicksort(
                arr, arrTexts, display, settings, pi + 1, high
            )

    quicksort(
        arr, arrTexts, display, settings, 0, len(arr) - 1
    )
    draw_array(display, arrTexts, settings)
    clock.tick(FREQUENCY_CLOCK)

