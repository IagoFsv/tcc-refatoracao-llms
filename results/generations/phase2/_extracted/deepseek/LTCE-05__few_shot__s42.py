"""Renders the help page of an editor into a text widget.

Public entry point: run(html, show=True, header='Intro', level=0). Do not
change its name or signature; the rest of the file may be freely
reorganized.
"""

from html.parser import HTMLParser


class HelpParser(HTMLParser):
    """Render help.html into a text widget.

    The overridden handle_xyz methods handle a subset of html tags.
    The supplied text should have the needed tag configurations.
    The behavior for unsupported tags, such as table, is undefined.
    If the tags generated by Sphinx change, this class, especially
    the handle_starttag and handle_endtags methods, might have to also.
    """
    def __init__(self, text):
        HTMLParser.__init__(self, convert_charrefs=True)
        self.text = text          # Text widget we're rendering into.
        self.tags = ''            # Current block level text tags to apply.
        self.chartags = ''        # Current character level text tags.
        self.show = False         # Exclude html page navigation.
        self.hdrlink = False      # Exclude html header links.
        self.level = 0            # Track indentation level.
        self.pre = False          # Displaying preformatted text?
        self.hprefix = ''         # Heading prefix  (like '25.5'?) to remove.
        self.nested_dl = False    # In a nested <dl>?
        self.simplelist = False   # In a simple list  (no double spacing)?
        self.toc = []             # Pair headers with text indexes for toc.
        self.header = ''          # Text within header tags for toc.
        self.prevtag = None       # Previous tag info  (opener?, tag).

    def indent(self, amt=1):
        "Change indent  (+1, 0, -1) and tags."
        self.level += amt
        self.tags = '' if self.level == 0 else 'l'+str(self.level)

    def handle_endtag(self, tag):
        "Handle endtags in help.html."
        if tag in  ['h1', 'h2', 'h3']:
            assert self.level == 0
            if self.show:
                indent = ('         ' if tag == 'h3' else
                          '     ' if tag == 'h2' else
                          '')
                self.toc.append((indent+self.header, self.text.index('insert')))
            self.tags = ''
        elif tag in  ['span', 'em']:
            self.chartags = ''
        elif tag == 'a':
            self.hdrlink = False
        elif tag == 'pre':
            self.pre = False
            self.tags = ''
        elif tag in  ['ul', 'dd', 'ol']:
            self.indent(-1)
        self.prevtag = (False, tag)


class _TextWidget:
    """Stands for the text widget: index('insert') returns successive positions."""

    def __init__(self):
        self.calls = 0

    def index(self, mark):
        self.calls += 1
        return f"{self.calls}.0"


def run(html, show=True, header="Intro", level=0):
    """Feeds the html to the parser, starting from the given state, and returns
    the state after the closing tags. Public entry point of this unit."""
    parser = HelpParser(_TextWidget())
    parser.show = show
    parser.header = header
    parser.level = level
    parser.tags = "start"
    parser.chartags = "em"
    parser.hdrlink = True
    parser.pre = True
    parser.feed(html)
    parser.close()
    return {
        "toc": parser.toc,
        "tags": parser.tags,
        "chartags": parser.chartags,
        "hdrlink": parser.hdrlink,
        "pre": parser.pre,
        "level": parser.level,
        "prevtag": parser.prevtag,
    }
