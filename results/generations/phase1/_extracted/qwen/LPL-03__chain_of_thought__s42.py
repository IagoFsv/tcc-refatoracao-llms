"""Animation of a sort, frame by frame.

Public entry point: run(values). Do not change its name or signature; the
rest of the file may be freely reorganized.

The screen and the clock are minimal versions. The screen keeps every frame
drawn (texts in the current order, highlighted positions, reference width
and height); the clock keeps the rate requested at each tick.
"""

FREQUENCY_CLOCK = 3


class _Text:
    """Already rendered text of an element."""

    def __init__(self, value):
        self.value = value


class _Screen:
    """Keeps the frames instead of drawing them."""

    def __init__(self):
        self.frames = []


class _Clock:
    """Keeps the rate of each tick instead of waiting."""

    def __init__(self):
        self.ticks = []

    def tick(self, framerate):
        self.ticks.append(framerate)


class _CompareElementsParams:
    """Parameter object for compare_elements function."""

    def __init__(self, display, arrTexts, width_reference, height_reference, arr, i, j):
        self.display = display
        self.arrTexts = arrTexts
        self.width_reference = width_reference
        self.height_reference = height_reference
        self.arr = arr
        self.i = i
        self.j = j


clock = _Clock()


def draw_array(display, arrTexts, width_rectangle, height_reference, poses_elevated=()):
    texts = tuple(text.value for text in arrTexts)
    display.frames.append((texts, tuple(poses_elevated), width_rectangle, height_reference))


def swap_elements(arr, arrText, i, j):
    arr[i], arr[j] = arr[j], arr[i]
    arrText[i], arrText[j] = arrText[j], arrText[i]


def compare_elements(params):
    width_reference = params.width_reference
    height_reference = params.height_reference
    arr = params.arr
    i = params.i
    j = params.j
    display = params.display
    arrTexts = params.arrTexts
    draw_array(display, arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)
    draw_array(display, arrTexts, width_reference, height_reference, [i, j])
    clock.tick(FREQUENCY_CLOCK)
    if (arr[i] > arr[j] and i < j) or (arr[i] < arr[j] and i > j):
        return False
    return True


def simulate_heapsort(arr, arrTexts, display, width_reference, height_reference):
    # generated by github copilot
    def heapify(arr, arrTexts, display, width_reference, height_reference, n, i):
        largest = i
        l = 2 * i + 1
        r = 2 * i + 2
        if l < n and compare_elements(
            _CompareElementsParams(
                display, arrTexts, width_reference, height_reference, arr, largest, l
            )
        ):
            largest = l
        if r < n and compare_elements(
            _CompareElementsParams(
                display, arrTexts, width_reference, height_reference, arr, largest, r
            )
        ):
            largest = r
        if largest != i:
            compare_elements(
                _CompareElementsParams(
                    display, arrTexts, width_reference, height_reference, arr, i, largest
                )
            )
            swap_elements(arr, arrTexts, i, largest)
            heapify(
                arr, arrTexts, display, width_reference, height_reference, n, largest
            )

    n = len(arr)
    for i in range(n, -1, -1):
        heapify(arr, arrTexts, display, width_reference, height_reference, n, i)
    for i in range(n - 1, 0, -1):
        swap_elements(arr, arrTexts, i, 0)
        heapify(arr, arrTexts, display, width_reference, height_reference, i, 0)
    draw_array(display, arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)


def run(values):
    """Sorts a copy of values, animating each step. Public entry point of this unit.

    Returns (sorted list, frames drawn, clock tick rates).
    Each frame is (texts, highlighted positions, width, height).
    """
    arr = list(values)
    texts = [_Text(str(x)) for x in arr]
    screen = _Screen()
    clock.ticks.clear()
    simulate_heapsort(arr, texts, screen, 40, 100)
    return arr, screen.frames, list(clock.ticks)
