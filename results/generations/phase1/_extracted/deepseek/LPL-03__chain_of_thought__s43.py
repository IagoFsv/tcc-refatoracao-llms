class CompareElementsParams:
    def __init__(self, display, arrTexts, width_reference, height_reference, arr, i, j):
        self.display = display
        self.arrTexts = arrTexts
        self.width_reference = width_reference
        self.height_reference = height_reference
        self.arr = arr
        self.i = i
        self.j = j


class SwapElementsParams:
    def __init__(self, arr, arrText, i, j):
        self.arr = arr
        self.arrText = arrText
        self.i = i
        self.j = j


def compare_elements(params: CompareElementsParams):
    draw_array(
        params.display,
        params.arrTexts,
        params.width_reference,
        params.height_reference
    )
    clock.tick(FREQUENCY_CLOCK)
    draw_array(
        params.display,
        params.arrTexts,
        params.width_reference,
        params.height_reference,
        [params.i, params.j]
    )
    clock.tick(FREQUENCY_CLOCK)
    if (params.arr[params.i] > params.arr[params.j] and params.i < params.j) or (
            params.arr[params.i] < params.arr[params.j] and params.i > params.j):
        return False
    return True


def heapify(arr, arrTexts, display, width_reference, height_reference, n, i, params: SwapElementsParams):
    largest = i
    l = 2 * i + 1
    r = 2 * i + 2
    if l < n and compare_elements(
            CompareElementsParams(display, arrTexts, width_reference, height_reference, arr, largest, l)
    ):
        largest = l
    if r < n and compare_elements(
            CompareElementsParams(display, arrTexts, width_reference, height_reference, arr, largest, r)
    ):
        largest = r
    if largest != i:
        compare_elements(
            SwapElementsParams(arr, arrTexts, i, largest)
        )
        swap_elements(arr, arrTexts, i, largest)
        heapify(
            arr, arrTexts, display, width_reference, height_reference, n, largest,
            SwapElementsParams(arr, arrTexts, i, largest)
        )


def simulate_heapsort(arr, arrTexts, display, width_reference, height_reference):
    # generated by github copilot
    n = len(arr)
    for i in range(n, -1, -1):
        heapify(arr, arrTexts, display, width_reference, height_reference, n, i, SwapElementsParams(arr, arrTexts, i, 0))
    for i in range(n - 1, 0, -1):
        swap_elements(arr, arrTexts, i, 0)
        heapify(arr, arrTexts, display, width_reference, height_reference, i, 0, SwapElementsParams(arr, arrTexts, i, 0))
    draw_array(display, arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)
