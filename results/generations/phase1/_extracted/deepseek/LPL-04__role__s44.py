"""Animation of a sort, frame by frame.

Public entry point: run(values). Do not change its name or signature; the
rest of the file may be freely reorganized.

The screen and the clock are minimal versions. The screen keeps every frame
drawn  (texts in the current order, highlighted positions, reference width
and height); the clock keeps the rate requested at each tick.
"""

FREQUENCY_CLOCK = 3


class Text:
    """Already rendered text of an element."""

    def __init__(self, value):
        self.value = value


class Screen:
    """Keeps the frames instead of drawing them."""

    def __init__(self):
        self.frames = []


class Clock:
    """Keeps the rate of each tick instead of waiting."""

    def __init__(self):
        self.ticks = []

    def tick(self, framerate):
        self.ticks.append(framerate)


clock = Clock()


def draw_array(display, arrTexts, width_rectangle, height_reference, poses_elevated=()):
    texts = tuple(text.value for text in arrTexts)
    display.frames.append((texts, tuple(poses_elevated), width_rectangle, height_reference))


def swap_elements(arr, arrText, i, j):
    arr[i], arr[j] = arr[j], arr[i]
    arrText[i], arrText[j] = arrText[j], arrText[i]


def compare_elements(display, arrTexts, params):
    width_reference, height_reference, arr, i, j = params
    draw_array(display, arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)
    draw_array(display, arrTexts, width_reference, height_reference, [i, j])
    clock.tick(FREQUENCY_CLOCK)
    if (arr[i] > arr[j] and i < j) or (arr[i] < arr[j] and i > j):
        return False
    return True


def compare_and_swap(display, arrTexts, params):
    width_reference, height_reference, arr, i, j = params
    swapped = False
    draw_array(display, arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)
    draw_array(display, arrTexts, width_reference, height_reference, [i, j])
    clock.tick(FREQUENCY_CLOCK)
    if (arr[i] > arr[j] and i < j) or (arr[i] < arr[j] and i > j):
        swap_elements(arr, arrTexts, i, j)
        draw_array(display, arrTexts, width_reference, height_reference, [i, j])
        clock.tick(FREQUENCY_CLOCK)
        swapped = True
    draw_array(display, arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)
    return swapped


def simulate_quicksort(arr, arrTexts, display, width_reference, height_reference):
    # generated by github copilot
    def partition(arr, arrTexts, display, width_reference, height_reference, low, high):
        i = low - 1
        params = (width_reference, height_reference, arr, i, j)
        for j in range(low, high):
            if compare_elements(display, arrTexts, params):
                i += 1
                if i != j:
                    compare_and_swap(display, arrTexts, params)
        if i + 1 != high:
            compare_and_swap(display, arrTexts, params)
        return i + 1

    def quicksort(arr, arrTexts, display, width_reference, height_reference, low, high):
        if low < high:
            pi = partition(arr, arrTexts, display, width_reference, height_reference, low, high)
            quicksort(arr, arrTexts, display, width_reference, height_reference, low, pi - 1)
            quicksort(arr, arrTexts, display, width_reference, height_reference, pi + 1, high)

    quicksort(arr, arrTexts, display, width_reference, height_reference, 0, len(arr) - 1)
    draw_array(display, arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)


def run(values):
    """Sorts a copy of values, animating each step. Public entry point of this unit.

    Returns  (sorted list, frames drawn, clock tick rates).
    Each frame is  (texts, highlighted positions, width, height).
    """
    arr = list(values)
    texts = [_Text(str(x)) for x in arr]
    screen = Screen()
    clock.ticks.clear()
    simulate_quicksort(arr, texts, screen, 40, 100)
    return arr, screen.frames, list(clock.ticks)
