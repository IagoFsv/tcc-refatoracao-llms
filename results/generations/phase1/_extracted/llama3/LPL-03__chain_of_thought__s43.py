"""Animation of a sort, frame by frame.

Public entry point: run(values). Do not change its name or signature; the
rest of the file may be freely reorganized.

The screen and the clock are minimal versions. The screen keeps every frame
drawn (texts in the current order, highlighted positions, reference width
and height); the clock keeps the rate requested at each tick.
"""

FREQUENCY_CLOCK = 3


class _Text:
    """Already rendered text of an element."""

    def __init__(self, value):
        self.value = value


class _Screen:
    """Keeps the frames instead of drawing them."""

    def __init__(self):
        self.frames = []


class _Clock:
    """Keeps the rate of each tick instead of waiting."""

    def __init__(self):
        self.ticks = []

    def tick(self, framerate):
        self.ticks.append(framerate)


class HeapsortOptions:
    def __init__(self, width_reference, height_reference, arrTexts):
        self.width_reference = width_reference
        self.height_reference = height_reference
        self.arrTexts = arrTexts


clock = _Clock()


def draw_array(display, texts, width_rectangle, height_reference):
    display.frames.append((texts, (), width_rectangle, height_reference))


def swap_elements(arr, arrText, i, j):
    arr[i], arr[j] = arr[j], arr[i]
    arrText[i], arrText[j] = arrText[j], arrText[i]


def compare_elements(display, options, i, j):
    draw_array(display, options.arrTexts, options.width_reference, options.height_reference)
    clock.tick(FREQUENCY_CLOCK)
    draw_array(display, options.arrTexts, options.width_reference, options.height_reference, [i, j])
    clock.tick(FREQUENCY_CLOCK)
    if (arr[i] > arr[j] and i < j) or (arr[i] < arr[j] and i > j):
        return False
    return True


def simulate_heapsort(arr, options, display):
    # generated by github copilot
    def heapify(arr, options, display, n, i):
        largest = i
        l = 2 * i + 1
        r = 2 * i + 2
        if l < n and compare_elements(display, options, largest, l):
            largest = l
        if r < n and compare_elements(display, options, largest, r):
            largest = r
        if largest != i:
            compare_elements(display, options, i, largest)
            swap_elements(arr, options.arrTexts, i, largest)
            heapify(arr, options, display, n, largest)

    n = len(arr)
    for i in range(n, -1, -1):
        heapify(arr, options, display, n, i)
    for i in range(n - 1, 0, -1):
        swap_elements(arr, options.arrTexts, i, 0)
        heapify(arr, options, display, i, 0)
    draw_array(display, options.arrTexts, options.width_reference, options.height_reference)
    clock.tick(FREQUENCY_CLOCK)


def run(values):
    """Sorts a copy of values, animating each step. Public entry point of this unit.

    Returns (sorted list, frames drawn, clock tick rates).
    Each frame is (texts, highlighted positions, width, height).
    """
    arr = list(values)
    texts = [_Text(str(x)) for x in arr]
    options = HeapsortOptions(40, 100, texts)
    screen = _Screen()
    clock.ticks.clear()
    simulate_heapsort(arr, options, screen)
    return arr, screen.frames, list(clock.ticks)
