class AnimationParameters:
    def __init__(self, display, arrTexts, width_reference, height_reference, *args):
        self.display = display
        self.arrTexts = arrTexts
        self.width_reference = width_reference
        self.height_reference = height_reference
        self.args = args

    def get_args(self):
        return self.args


FREQUENCY_CLOCK = 3


class _Texto:
    """Texto já renderizado de um elemento."""

    def __init__(self, valor):
        self.valor = valor


class _Tela:
    """Guarda os quadros em vez de desenhar."""

    def __init__(self):
        self.quadros = []


class _Relogio:
    """Guarda a taxa de cada tick em vez de esperar."""

    def __init__(self):
        self.ticks = []

    def tick(self, framerate):
        self.ticks.append(framerate)


clock = _Relogio()


def draw_array(display, arrTexts, width_rectangle, height_reference, poses_elevated=()):
    textos = tuple(texto.valor for texto in arrTexts)
    display.quadros.append((textos, tuple(poses_elevated), width_rectangle, height_reference))


def swap_elements(arr, arrText, i, j):
    arr[i], arr[j] = arr[j], arr[i]
    arrText[i], arrText[j] = arrText[j], arrText[i]


def compare_elements(params):
    width_reference, height_reference, arr, i, j = params.get_args()
    draw_array(params.display, params.arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)
    draw_array(params.display, params.arrTexts, width_reference, height_reference, [i, j])
    clock.tick(FREQUENCY_CLOCK)
    if (arr[i] > arr[j] and i < j) or (arr[i] < arr[j] and i > j):
        return False
    return True


def compare_and_swap(params):
    width_reference, height_reference, arr, i, j = params.get_args()
    swapped = False
    draw_array(params.display, params.arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)
    draw_array(params.display, params.arrTexts, width_reference, height_reference, [i, j])
    clock.tick(FREQUENCY_CLOCK)
    if (arr[i] > arr[j] and i < j) or (arr[i] < arr[j] and i > j):
        swap_elements(arr, params.arrTexts, i, j)
        draw_array(params.display, params.arrTexts, width_reference, height_reference, [i, j])
        clock.tick(FREQUENCY_CLOCK)
        swapped = True
    draw_array(params.display, params.arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)
    return swapped


def simulate_quicksort(arr, arrTexts, display, width_reference, height_reference):
    # generated by github copilot
    def partition(arr, arrTexts, display, width_reference, height_reference, low, high):
        i = low - 1
        # pivot = arr[high]
        for j in range(low, high):
            if compare_elements(AnimationParameters(display, arrTexts, width_reference, height_reference, arr, j, high)):
                i += 1
                if i != j:
                    compare_and_swap(AnimationParameters(display, arrTexts, width_reference, height_reference, arr, i, j))
        if i + 1 != high:
            compare_and_swap(AnimationParameters(display, arrTexts, width_reference, height_reference, arr, i + 1, high))
        return i + 1

    def quicksort(arr, arrTexts, display, width_reference, height_reference, low, high):
        if low < high:
            pi = partition(arr, arrTexts, display, width_reference, height_reference, low, high)
            quicksort(arr, arrTexts, display, width_reference, height_reference, low, pi - 1)
            quicksort(arr, arrTexts, display, width_reference, height_reference, pi + 1, high)

    quicksort(arr, arrTexts, display, width_reference, height_reference, 0, len(arr) - 1)
    draw_array(display, arrTexts, width_reference, height_reference)
    clock.tick(FREQUENCY_CLOCK)


def executar(valores):
    """Ordena uma copia de valores, animando cada passo. Ponto de entrada publico.

    Devolve (lista ordenada, quadros desenhados, taxas dos ticks do relogio).
    Cada quadro e (textos, posicoes destacadas, largura, altura).
    """
    arr = list(valores)
    textos = [_Texto(str(x)) for x in arr]
    tela = _Tela()
    clock.ticks.clear()
    simulate_quicksort(arr, textos, tela, 40, 100)
    return arr, tela.quadros, list(clock.ticks)
