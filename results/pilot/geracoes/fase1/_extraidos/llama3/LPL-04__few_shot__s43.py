from dataclasses import dataclass, asdict

@dataclass
class Texto:
    valor: str

@dataclass
class Quadro:
    textos: tuple
    poses_elevated: tuple
    width_rectangle: int
    height_reference: int

@dataclass
class Relogio:
    ticks: list

class Animacao:
    def __init__(self):
        self.quadros = []

    def draw_array(self, arrTexts, width_rectangle, height_reference, poses_elevated=()):
        self.quadros.append(Quadro(tuple(texto.valor for texto in arrTexts), poses_elevated, width_rectangle, height_reference))

    def tick(self, framerate):
        self.quadros.append(framerate)

def executar(valores):
    animacao = Animacao()
    textos = tuple(Texto(str(x)) for x in valores)
    clock = Relogio()
    clock.ticks.clear()
    simulate_quicksort(valores, textos, animacao, 40, 100)
    return valores, animacao.quadros, clock.ticks

