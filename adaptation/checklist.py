"""Automatic checklist of the adapted instances (step 2).

For each instance, checks:
  diff         the snippet of the original (whole enclosing function) appears
               identical, exactly once, in the unit;
  pysmell      the detections of the study smells inside the snippet are the
               same as in the original, and there is none outside it
               (scaffolding);
  pytest       exactly 3 tests (typical, edge, invalid), all passing;
  mutation     mutants generated by fixed rules, only inside the snippet; at
               least one must be killed by the tests;
  neutrality   outside the snippet, the unit does not mention the study, the
               smell, metrics or the origin of the code;
  contract     run() exists, the docstring states the contract and the
               provenance record has the mandatory fields.

Usage:
    python -m adaptation.checklist                  # every instance
    python -m adaptation.checklist LLF-01 MNC-01    # only these
    --no-mutation    skips mutation (faster)

Writes instances/checklist.csv, one row per instance. Rows of instances that
were not run now are kept as they were.
"""

import argparse
import ast
import csv
import datetime
import importlib.metadata
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import tempfile
import tokenize
import warnings
import xml.etree.ElementTree as ET
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from pysmell.detect import detect_file

ROOT = Path(__file__).resolve().parent.parent
SELECTION = ROOT / "data" / "selection" / "instances_zhang.csv"
DATASET = ROOT / "data" / "dataset_zhang" / "dataset" / "files"
INSTANCES = ROOT / "instances"
TABLE = INSTANCES / "checklist.csv"

# Provenance record of each instance and the keys the checklist reads.
ORIGIN_FILE = "origin.json"
ORIGIN_FIELDS = ("id", "smell", "file", "entry_point", "pinned_behavior", "adaptation_check")
ORIGIN_SAME_AS_SELECTION = {"id": "id", "smell": "smell", "file": "file"}
ORIGIN_SNIPPET_LINES = "snippet_lines"

PACKAGES = ("pytest", "pandas", "tqdm", "numpy", "scikit-image", "scipy", "requests", "toml", "invoke",
            "beautifulsoup4", "termcolor")
MUTANT_TIMEOUT = 30  # seconds; a mutant that times out counts as killed
TEST_PREFIXES = ("test_typical_", "test_edge_", "test_invalid_")
CONTRACT = ("Public entry point: run(", "Do not change its name or signature")
# Words that, outside the snippet, would give the model a hint about the study
# or the origin of the code. They match at the start of a word ("refator"
# matches "refatorar").
HINTS = re.compile(
    r"\b(smell|refator|refactor|pysmell|metrica|estudo|tcc|copilot|chatgpt|"
    r"gpt|llm|limiar|zhang|metric|study|threshold)", re.IGNORECASE)

COLUMNS = ["id", "smell", "approved", "diff", "pysmell", "pytest", "mutation",
           "mutants", "neutrality", "contract", "surviving_mutants",
           "notes", "date", "environment"]


# ---------------------------------------------------------------- reading

def _read_lines(path):
    """Lines of the file, without line endings. Honors the declared encoding."""
    try:
        with tokenize.open(path) as fh:
            return fh.read().splitlines()
    except (UnicodeDecodeError, SyntaxError):
        return Path(path).read_text(encoding="latin-1").splitlines()


def _parse(text):
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", SyntaxWarning)
        return ast.parse(text)


def _selection():
    with open(SELECTION, encoding="utf-8", newline="") as fh:
        return {row["id"]: row for row in csv.DictReader(fh)}


def _paths(inst):
    folder = INSTANCES / inst["smell"] / inst["id"]
    base = inst["id"].replace("-", "_")
    return folder, folder / f"{base}.py", folder / f"test_{base}.py", folder / ORIGIN_FILE


def _environment():
    versions = [f"Python {platform.python_version()}"]
    for package in PACKAGES:
        try:
            versions.append(f"{package} {importlib.metadata.version(package)}")
        except importlib.metadata.PackageNotFoundError:
            versions.append(f"{package} missing")
    return "; ".join(versions)


# ---------------------------------------------------------------- 1. diff

def _original_snippet(inst, origin):
    """(start, end, lines) of the snippet in the original, lines counted from 1.

    Function: from the first decorator to the last line of the body, found
    through the line of the def. Module-level code (<module>) has no function
    node; the range comes from the provenance record.
    """
    lines = _read_lines(DATASET / inst["file"])
    if ORIGIN_SNIPPET_LINES in origin:
        start, end = origin[ORIGIN_SNIPPET_LINES]
        return start, end, lines[start - 1:end]
    if inst["function"] == "<module>":
        raise ValueError(f"<module> instance: set {ORIGIN_SNIPPET_LINES} in {ORIGIN_FILE}")
    target = int(inst["function_line"])
    for node in ast.walk(_parse("\n".join(lines))):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.lineno == target:
            start = min([node.lineno] + [d.lineno for d in node.decorator_list])
            return start, node.end_lineno, lines[start - 1:node.end_lineno]
    raise ValueError(f"no function starts at line {target} of the original")


def _locate(block, lines):
    """Lines (1-based) where the block starts inside `lines`."""
    n = len(block)
    return [i + 1 for i in range(len(lines) - n + 1) if lines[i:i + n] == block]


# ---------------------------------------------------------------- 2. pysmell

def _detections(path, start, end):
    """Detections of the study smells, split into inside and outside the snippet.

    Inside the snippet, the line becomes relative to the start, to compare
    original and unit.
    """
    inside, outside = [], []
    for d in detect_file(str(path)):
        if start <= d["line"] <= end:
            inside.append((d["smell"], d["line"] - start, d["metrics"]))
        else:
            outside.append(f"{d['smell']} L{d['line']} {d['metrics']}")
    return sorted(inside), outside


# ---------------------------------------------------------------- 3. pytest

def _pytest(folder, *extra, timeout=None):
    cmd = [sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", *extra, str(folder)]
    return subprocess.run(cmd, cwd=folder, capture_output=True, text=True, timeout=timeout)


def _test_results(folder):
    """{test_name: passed} read from the pytest junit report."""
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        junit = Path(tmp) / "junit.xml"
        _pytest(folder, f"--junitxml={junit}")
        if not junit.exists():
            return {}
        cases = ET.parse(junit).getroot().iter("testcase")
        return {c.get("name"): not any(f.tag in ("failure", "error", "skipped") for f in c)
                for c in cases}


# ---------------------------------------------------------------- 4. mutation

_SWAP_CMP = {ast.Eq: ast.NotEq, ast.NotEq: ast.Eq, ast.Lt: ast.GtE, ast.GtE: ast.Lt,
             ast.Gt: ast.LtE, ast.LtE: ast.Gt, ast.In: ast.NotIn, ast.NotIn: ast.In,
             ast.Is: ast.IsNot, ast.IsNot: ast.Is}
_SWAP_BIN = {ast.Add: ast.Sub, ast.Sub: ast.Add, ast.Mult: ast.Div, ast.Div: ast.Mult,
             ast.FloorDiv: ast.Mult, ast.Mod: ast.FloorDiv}
_SWAP_BOOL = {ast.And: ast.Or, ast.Or: ast.And}


class _Mutator(ast.NodeTransformer):
    """Walks the tree in a fixed order and numbers the mutation points.

    With target=None it only counts and describes the points. With target=k
    it applies only the k-th mutation. Children are always visited before the
    node, so the numbering is the same in both passes.

    Rules: invert comparison (== to !=, < to >=, in to not in...), swap
    arithmetic operator (+ to -, * to /...), swap and with or, remove not,
    invert True/False, add 1 to a number, replace a statement (assignment,
    bare call, return, raise) with pass.
    """

    def __init__(self, start, end, offset, target=None):
        self.start, self.end, self.offset, self.target = start, end, offset, target
        self.points = []

    def _point(self, node, description):
        """Records the point if it is inside the snippet; True if it is the one to mutate."""
        line = getattr(node, "lineno", 0)
        if not self.start <= line <= self.end:
            return False
        self.points.append(f"L{line + self.offset}:{node.col_offset} {description}")
        return len(self.points) - 1 == self.target

    def visit_Compare(self, node):
        self.generic_visit(node)
        for i, op in enumerate(node.ops):
            swap = _SWAP_CMP.get(type(op))
            if swap and self._point(node, f"{type(op).__name__}->{swap.__name__}"):
                node.ops[i] = swap()
        return node

    def _operator(self, node):
        swap = _SWAP_BIN.get(type(node.op))
        if swap and self._point(node, f"{type(node.op).__name__}->{swap.__name__}"):
            node.op = swap()

    def visit_BinOp(self, node):
        self.generic_visit(node)
        self._operator(node)
        return node

    def visit_BoolOp(self, node):
        self.generic_visit(node)
        swap = _SWAP_BOOL[type(node.op)]
        if self._point(node, f"{type(node.op).__name__}->{swap.__name__}"):
            node.op = swap()
        return node

    def visit_UnaryOp(self, node):
        self.generic_visit(node)
        if isinstance(node.op, ast.Not) and self._point(node, "remove not"):
            return node.operand
        return node

    def visit_Constant(self, node):
        if isinstance(node.value, bool):
            if self._point(node, f"{node.value}->{not node.value}"):
                return ast.copy_location(ast.Constant(not node.value), node)
        elif isinstance(node.value, (int, float)):
            if self._point(node, f"{node.value}->{node.value + 1}"):
                return ast.copy_location(ast.Constant(node.value + 1), node)
        return node

    def _delete(self, node):
        if self._point(node, f"delete {type(node).__name__}"):
            return ast.copy_location(ast.Pass(), node)
        return node

    def visit_AugAssign(self, node):
        self.generic_visit(node)
        self._operator(node)
        return self._delete(node)

    def visit_Expr(self, node):
        self.generic_visit(node)
        if isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            return node  # docstring
        return self._delete(node)

    def _visit_and_delete(self, node):
        self.generic_visit(node)
        return self._delete(node)

    visit_Assign = visit_AnnAssign = visit_Return = visit_Raise = _visit_and_delete


def _mutants(source, start, end, offset):
    """List of (description, code), one mutant per point of the snippet."""
    counter = _Mutator(start, end, offset)
    counter.visit(_parse(source))
    found = []
    for k, description in enumerate(counter.points):
        tree = _Mutator(start, end, offset, target=k).visit(_parse(source))
        found.append((description, ast.unparse(ast.fix_missing_locations(tree))))
    return found


def _run_mutant(code, unit_name, test):
    """'killed', 'survived' or 'timeout' (counts as killed)."""
    with tempfile.TemporaryDirectory(ignore_cleanup_errors=True) as tmp:
        Path(tmp, unit_name).write_text(code, encoding="utf-8")
        shutil.copy(test, tmp)
        try:
            r = _pytest(Path(tmp), "-x", timeout=MUTANT_TIMEOUT)
        except subprocess.TimeoutExpired:
            return "timeout"
    return "survived" if r.returncode == 0 else "killed"


def _mutation(unit, test, start, end, offset):
    """(ok, 'killed/total', survivors, note)."""
    source = unit.read_text(encoding="utf-8")
    # Baseline: the unit rewritten by ast.unparse, without mutation, must pass.
    # Otherwise the rewrite (which loses comments) would invalidate mutation.
    base = _run_mutant(ast.unparse(_parse(source)), unit.name, test)
    if base != "survived":
        return False, "", [], "the rewritten unit without mutation already fails the tests"
    mutants = _mutants(source, start, end, offset)
    if not mutants:
        return False, "0/0", [], "no mutation point in the snippet"
    with ThreadPoolExecutor(max_workers=os.cpu_count()) as pool:
        results = list(pool.map(lambda m: _run_mutant(m[1], unit.name, test), mutants))
    survivors = [d for (d, _), r in zip(mutants, results) if r == "survived"]
    killed = len(mutants) - len(survivors)
    return killed >= 1, f"{killed}/{len(mutants)}", survivors, ""


# ---------------------------------------------------------------- 5 and 6

def _neutrality(lines, ustart, uend):
    found = []
    for n, line in enumerate(lines, start=1):
        if ustart <= n <= uend:
            continue
        for m in HINTS.finditer(line):
            found.append(f"L{n} '{m.group(0)}'")
    return found


def _contract(inst, unit, origin_file):
    problems = []
    tree = _parse(unit.read_text(encoding="utf-8"))
    doc = " ".join((ast.get_docstring(tree) or "").split())  # ignores line breaks
    problems += [f"docstring without '{phrase}'" for phrase in CONTRACT if phrase not in doc]
    if not any(isinstance(n, ast.FunctionDef) and n.name == "run" for n in tree.body):
        problems.append("no run() at module level")
    if not origin_file.exists():
        return problems + [f"no {ORIGIN_FILE}"]
    origin = json.loads(origin_file.read_text(encoding="utf-8"))
    problems += [f"{ORIGIN_FILE} without '{f}'" for f in ORIGIN_FIELDS if f not in origin]
    for field, column in ORIGIN_SAME_AS_SELECTION.items():
        if field in origin and origin[field] != inst[column]:
            problems.append(f"{ORIGIN_FILE} {field}={origin[field]!r}, selection says {inst[column]!r}")
    return problems


# ---------------------------------------------------------------- instance

def check(inst, with_mutation=True):
    """Runs the checklist of one instance and returns the table row."""
    row = {c: "" for c in COLUMNS}
    row.update(id=inst["id"], smell=inst["smell"],
               date=datetime.date.today().isoformat(), environment=_environment())
    notes = []
    folder, unit, test, origin_file = _paths(inst)
    if not unit.exists():
        row.update(approved="no", notes=f"no unit at {unit.relative_to(ROOT)}")
        return row, []

    origin = json.loads(origin_file.read_text(encoding="utf-8")) if origin_file.exists() else {}
    unit_lines = _read_lines(unit)

    # 1. diff
    try:
        start, end, block = _original_snippet(inst, origin)
        found = _locate(block, unit_lines)
        if len(found) == 1:
            ustart, uend = found[0], found[0] + len(block) - 1
            row["diff"] = "ok"
        else:
            ustart = None
            row["diff"] = "fail"
            notes.append(f"snippet (lines {start}-{end}) found {len(found)} times in the unit")
    except (ValueError, SyntaxError) as error:
        ustart = None
        row["diff"] = "error"
        notes.append(f"diff: {error}")

    # 2. pysmell (needs the located snippet)
    if ustart is None:
        row["pysmell"] = "n/a"
    else:
        orig_inside, _ = _detections(DATASET / inst["file"], start, end)
        unit_inside, unit_outside = _detections(unit, ustart, uend)
        expected = {int(n) - start for n in inst["lines"].split(";")}
        of_smell = {rel for s, rel, _ in orig_inside if s == inst["smell"]}
        ok = orig_inside == unit_inside and not unit_outside and expected <= of_smell
        row["pysmell"] = "ok" if ok else "fail"
        if orig_inside != unit_inside:
            notes.append(f"pysmell in the snippet differs: original {orig_inside}, unit {unit_inside}")
        if unit_outside:
            notes.append("pysmell outside the snippet: " + ", ".join(unit_outside))
        if not expected <= of_smell:
            notes.append(f"selected lines without a {inst['smell']} detection in the original")

    # 3. pytest
    if not test.exists():
        row["pytest"] = "fail"
        notes.append("no test file")
    else:
        tests = _test_results(folder)
        names = sorted(tests)
        prefixes_ok = (len(names) == 3 and
                       all(any(n.startswith(p) for n in names) for p in TEST_PREFIXES))
        passed = sum(tests.values())
        row["pytest"] = "ok" if prefixes_ok and passed == 3 else "fail"
        if row["pytest"] != "ok":
            notes.append(f"pytest: {passed} of {len(names)} passed; tests {names}")

    # 4. mutation
    survivors = []
    if not with_mutation:
        row["mutation"] = "skipped"
    elif ustart is None or row["pytest"] != "ok":
        row["mutation"] = "n/a"
    else:
        ok, score, survivors, note = _mutation(unit, test, ustart, uend, start - ustart)
        row.update(mutation="ok" if ok else "fail", mutants=score,
                   surviving_mutants=" | ".join(survivors))
        if note:
            notes.append(f"mutation: {note}")

    # 5. neutrality
    if ustart is None:
        row["neutrality"] = "n/a"
    else:
        hints = _neutrality(unit_lines, ustart, uend)
        row["neutrality"] = "ok" if not hints else "fail"
        if hints:
            notes.append("hints outside the snippet: " + ", ".join(hints))

    # 6. contract
    problems = _contract(inst, unit, origin_file)
    row["contract"] = "ok" if not problems else "fail"
    notes += problems

    items = ("diff", "pysmell", "pytest", "neutrality", "contract")
    approved = all(row[i] == "ok" for i in items) and row["mutation"] in ("ok", "skipped")
    row["approved"] = "yes" if approved else "no"
    row["notes"] = " | ".join(notes)
    return row, survivors


# ---------------------------------------------------------------- table

def _write(new_rows, order):
    existing = {}
    if TABLE.exists():
        with open(TABLE, encoding="utf-8", newline="") as fh:
            existing = {r["id"]: r for r in csv.DictReader(fh)}
    existing.update({r["id"]: r for r in new_rows})
    with open(TABLE, "w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=COLUMNS, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(existing[i] for i in order if i in existing)


def _summary(row):
    items = [f"{c} {row[c]}" for c in ("diff", "pysmell", "pytest", "neutrality", "contract")]
    mut = row["mutation"] + (f" ({row['mutants']})" if row["mutants"] else "")
    return f"{row['id']:8} {' | '.join(items)} | mutation {mut}  => {row['approved'].upper()}"


def main(argv=None):
    p = argparse.ArgumentParser(description="Automatic checklist of the adapted instances.")
    p.add_argument("ids", nargs="*", help="instance ids (default: every one with a folder)")
    p.add_argument("--no-mutation", action="store_true", help="skip mutation")
    args = p.parse_args(argv)

    selection = _selection()
    unknown = [i for i in args.ids if i not in selection]
    if unknown:
        p.error(f"ids not in the selection: {', '.join(unknown)}")

    ids = args.ids or [i for i, inst in selection.items() if _paths(inst)[0].exists()]
    rows = []
    for i in ids:
        row, survivors = check(selection[i], with_mutation=not args.no_mutation)
        rows.append(row)
        print(_summary(row))
        if row["notes"]:
            for note in row["notes"].split(" | "):
                print(f"         ! {note}")
        for s in survivors:
            print(f"         surviving mutant: {s}")
    _write(rows, list(selection))

    everything = _pytest(INSTANCES)
    summary = (everything.stdout.strip().splitlines() or ["(no output)"])[-1]
    print(f"\npytest instances (all together): {summary}")
    print(f"table: {TABLE.relative_to(ROOT)}")
    failed = [r["id"] for r in rows if r["approved"] != "yes"]
    if failed:
        print(f"failed: {', '.join(failed)}")
    return 1 if failed or everything.returncode != 0 else 0


if __name__ == "__main__":
    sys.exit(main())
